-- Campus Eats schema (PostgreSQL). All money is stored as integer cents.
-- Safe to run repeatedly: every statement is CREATE ... IF NOT EXISTS.

CREATE TABLE IF NOT EXISTS categories (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug        VARCHAR(64)  NOT NULL UNIQUE,
  name        VARCHAR(100) NOT NULL,
  blurb       VARCHAR(255),
  note        VARCHAR(255),                 -- board footnote, e.g. "Served with toast"
  image       VARCHAR(255),
  accent      TEXT NOT NULL DEFAULT 'red' CHECK (accent IN ('red', 'green', 'blue')),
  sort_order  INT NOT NULL DEFAULT 0
);

-- Bread formats (Roll / Wrap / Hero / Panini) priced once per category.
-- An item in such a category costs size price + items.surcharge_cents.
CREATE TABLE IF NOT EXISTS category_sizes (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id  INT NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
  name         VARCHAR(50) NOT NULL,
  price_cents  INT NOT NULL CHECK (price_cents >= 0),
  sort_order   INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS items (
  id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id      INT NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
  code             VARCHAR(8),              -- board code: C1, H14, F2 ...
  name             VARCHAR(120) NOT NULL,
  description      VARCHAR(255),
  base_price_cents INT CHECK (base_price_cents >= 0),   -- NULL when priced by category sizes or item variants
  surcharge_cents  INT NOT NULL DEFAULT 0 CHECK (surcharge_cents >= 0),
  dietary          TEXT NOT NULL DEFAULT 'none' CHECK (dietary IN ('none', 'vegetarian', 'vegan')),
  is_featured      BOOLEAN NOT NULL DEFAULT FALSE,
  is_available     BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order       INT NOT NULL DEFAULT 0,
  UNIQUE (category_id, code)
);

-- Item-specific priced choices ("with Meat", muffin flavors, bagel spreads).
CREATE TABLE IF NOT EXISTS item_variants (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id      INT NOT NULL REFERENCES items (id) ON DELETE CASCADE,
  name         VARCHAR(100) NOT NULL,
  price_cents  INT NOT NULL CHECK (price_cents >= 0),
  sort_order   INT NOT NULL DEFAULT 0
);

-- Add-ons belong to a category (breakfast, omelettes, smashburgers).
CREATE TABLE IF NOT EXISTS addons (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id  INT NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
  name         VARCHAR(100) NOT NULL,
  price_cents  INT NOT NULL CHECK (price_cents >= 0),
  sort_order   INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS orders (
  id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code            VARCHAR(12)  NOT NULL UNIQUE,   -- public pickup code, e.g. CE-7K3QF9
  customer_name   VARCHAR(100) NOT NULL,
  customer_phone  VARCHAR(30)  NOT NULL,
  customer_email  VARCHAR(190),
  notes           VARCHAR(500),
  status          TEXT NOT NULL DEFAULT 'received'
                  CHECK (status IN ('received', 'preparing', 'ready', 'completed', 'cancelled')),
  subtotal_cents  INT NOT NULL CHECK (subtotal_cents >= 0),
  tax_cents       INT NOT NULL DEFAULT 0 CHECK (tax_cents >= 0),
  total_cents     INT NOT NULL CHECK (total_cents >= 0),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()   -- set by setOrderStatus
);

CREATE INDEX IF NOT EXISTS idx_orders_status_created ON orders (status, created_at);

-- Order lines copy the name and price at the time of purchase, so later menu
-- edits (or a reseed) never change what a past order says.
CREATE TABLE IF NOT EXISTS order_items (
  id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id          INT NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  item_id           INT REFERENCES items (id) ON DELETE SET NULL,
  item_code         VARCHAR(8),
  item_name         VARCHAR(120) NOT NULL,
  category_name     VARCHAR(100) NOT NULL,       -- several items share a name ("Veggie" omelette vs burger)
  option_name       VARCHAR(100),
  unit_price_cents  INT NOT NULL CHECK (unit_price_cents >= 0),   -- option price + add-ons, for one unit
  quantity          INT NOT NULL CHECK (quantity >= 0),
  line_total_cents  INT NOT NULL CHECK (line_total_cents >= 0),
  notes             VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS order_item_addons (
  id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_item_id  INT NOT NULL REFERENCES order_items (id) ON DELETE CASCADE,
  addon_name     VARCHAR(100) NOT NULL,
  price_cents    INT NOT NULL CHECK (price_cents >= 0)
);
